// @ts-check
/**
 * commit-msg hook: the subject must follow Conventional Commits, because
 * release-please builds CHANGELOG.md and the version number from it.
 * Usage: node tools/check-commit-msg.js <path-to-COMMIT_EDITMSG>
 */
import { readFileSync } from 'node:fs';

const TYPES = ['feat', 'fix', 'perf', 'docs', 'refactor', 'test', 'build', 'ci', 'chore', 'style', 'revert'];
const PATTERN = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9-]+\\))?!?: [^A-Z].*[^.]$`);

const file = process.argv[2];
if (!file) {
  console.error('usage: check-commit-msg.js <commit message file>');
  process.exit(2);
}
const subject = readFileSync(file, 'utf8').split('\n')[0].trim();

// Merge and revert commits generated by git are fine as they are.
if (/^(Merge|Revert) /.test(subject) || PATTERN.test(subject)) process.exit(0);

console.error(`Commit subject does not follow Conventional Commits:\n\n  ${subject}\n
Expected: <type>(<scope>): <subject>   e.g. "fix(vote): reset slider after voting"
Types: ${TYPES.join(', ')}. Lower-case start, no trailing period. See CONTRIBUTING.md.`);
process.exit(1);
